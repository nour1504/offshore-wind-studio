export type TermId = keyof typeof glossary.en.defs;

/** A technical word with its definition on hover or focus. */
export function Term({ id, children }: { id: TermId; children?: ReactNode }) {
  const t = useT(glossary);
  return (
    <Tooltip label={t(`defs.${id}`)} maw={300} multiline events={{ hover: true, focus: true, touch: true }}>
      <Text component="span" inherit tabIndex={0} style={{ cursor: "help", display: "inline-flex", alignItems: "center", gap: 4 }}>
        {children ?? t(`words.${id}`)}
        <IconInfoCircle size={13} style={{ color: "var(--ows-muted)", flexShrink: 0 }} aria-hidden />
      </Text>
    </Tooltip>
  );
}
